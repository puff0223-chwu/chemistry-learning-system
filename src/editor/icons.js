export const ICON_CATEGORIES = Object.keys(RAW)

// [{ emoji, words: ['鑰匙', 'key'], category }]
export const ICON_LIBRARY = Object.entries(RAW).flatMap(([category, lines]) =>
  lines.map((line) => {
    const [emoji, ...words] = line.split(' ')
    return { emoji, words, category }
  }),
)

export function searchIcons(query, category) {
  const q = query.trim().toLowerCase()
  return ICON_LIBRARY.filter((i) => (!category || i.category === category) && (!q || i.words.some((w) => w.toLowerCase().includes(q))))
}

// The first search word is the icon's everyday name; used to name a freshly picked icon object.
export function iconName(emoji) {
  return ICON_LIBRARY.find((i) => i.emoji === emoji)?.words[0] ?? '圖示'
}
